//! Code generation: the design as ordinary OpenTofu / Terraform HCL (AWS provider 5), one resource per block, each with a comment
//! pointing back to the design block and the tags managed-by = aws-infra-builder, project and design-block. The files are plain
//! enough to take and run without the app.

use crate::model::{instance_type, parse_ports, Design, Node, OS};
use std::collections::BTreeMap;

/// file name -> contents
pub type Files = BTreeMap<String, String>;

fn p<'a>(n: &'a Node, key: &str) -> &'a str {
    n.params.get(key).and_then(|v| v.as_str()).unwrap_or("")
}

/// a string in HCL quotes
fn q(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace("${", "$${"))
}

/// a project name as a tag value / resource-name prefix
pub fn slug(name: &str) -> String {
    let s: String = name.trim().chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '-' }).collect();
    let s = s.trim_matches('-').to_string();
    let mut out = String::new();
    for c in s.chars() {
        if c == '-' && out.ends_with('-') {
            continue;
        }
        out.push(c);
    }
    if out.is_empty() { "aws-infra-builder".into() } else { out }
}

/// the AMI data source an instance needs: (data name, owner, name pattern)
fn ami_for(os: &str, arch: &str) -> (String, String, String) {
    let o = OS.iter().find(|o| o.0 == os).unwrap_or(&OS[0]);
    let ubuntu_arch = if arch == "arm64" { "arm64" } else { "amd64" };
    let pattern = o.3.replace("{arch}", if o.0 == "debian" { ubuntu_arch } else { arch }).replace("{ubuntu_arch}", ubuntu_arch);
    (format!("{}_{}", o.0, arch.replace('-', "_")), o.2.to_string(), pattern)
}

pub fn generate(d: &Design) -> Files {
    generate_with(d, &std::collections::HashSet::new())
}

/// `managed` = the ids already in the state file: those get no import block (OpenTofu refuses to import what it manages)
pub fn generate_with(d: &Design, managed: &std::collections::HashSet<String>) -> Files {
    let mut imports: Vec<(String, String)> = vec![];
    let mut adopt = |to: String, id: &str| {
        let id = id.trim();
        if !id.is_empty() && !managed.contains(id) && !imports.iter().any(|(t, _)| *t == to) {
            imports.push((to, id.to_string()));
        }
    };
    let analysis = crate::checks::analyse(d);
    let project = slug(if d.name.trim().is_empty() { "aws-infra-builder" } else { &d.name });
    let label = |id: &str| d.node(id).map(|n| n.label.clone()).unwrap_or_else(|| "missing".into());
    let group_ref = |g: &Node| format!("{}.{}", if g.params.get("aws_default").and_then(|v| v.as_bool()).unwrap_or(false) { "aws_default_security_group" } else { "aws_security_group" }, g.label);
    let sg_ref = |id: &str| d.node(id).map(group_ref).unwrap_or_else(|| format!("aws_security_group.{}", label(id)));
    let tags = |n: &Node, extra: &[(&str, &str)]| -> String {
        let mut t = vec![format!("Name = \"${{var.project}}-{}\"", n.label), format!("\"design-block\" = {}", q(&n.label))];
        for (k, v) in extra {
            t.push(format!("{k} = {}", q(v)));
        }
        format!("  tags = {{ {} }}\n", t.join(", "))
    };

    let mut m = String::new();
    m.push_str(&format!("# main.tf: generated by AWS Infra Builder from the design {}.\n", q(&d.name)));
    m.push_str("# Each resource names the design block it comes from; change the design and generate again, or take these files and run\n# them on their own with OpenTofu or Terraform (`tofu init && tofu plan`).\n");
    if !analysis.ok {
        m.push_str(&format!("#\n# THE DESIGN HAS {} ERROR{}: fix them in the app before applying this.\n", analysis.errors, if analysis.errors == 1 { "" } else { "S" }));
        for pr in analysis.problems.iter().take(20) {
            m.push_str(&format!("#   - {pr}\n"));
        }
    }
    let has_lambda = d.nodes.iter().any(|n| n.kind == "lambda");
    m.push_str(&format!("\nterraform {{\n  required_version = \">= 1.6\"\n  required_providers {{\n    aws = {{\n      source  = \"hashicorp/aws\"\n      version = \"~> 5.0\"\n    }}\n{}  }}\n}}\n\n",
        if has_lambda { "    archive = {\n      source  = \"hashicorp/archive\"\n      version = \"~> 2.4\"\n    }\n" } else { "" }));
    m.push_str("provider \"aws\" {\n  region = var.region\n  default_tags {\n    tags = {\n      \"managed-by\" = \"aws-infra-builder\"\n      project      = var.project\n    }\n  }\n}\n");

    // AMIs: one data source per OS × architecture in use
    let mut amis: BTreeMap<String, (String, String)> = BTreeMap::new();
    for n in d.nodes.iter().filter(|n| (n.kind == "ec2" || n.kind == "asg") && p(n, "image_id").trim().is_empty()) {
        let arch = instance_type(p(n, "type")).map(|t| t.3).unwrap_or("x86_64");
        let (name, owner, pattern) = ami_for(p(n, "os"), arch);
        amis.insert(name, (owner, pattern));
    }
    for (name, (owner, pattern)) in &amis {
        m.push_str(&format!("\n# the newest {} image\ndata \"aws_ami\" \"{name}\" {{\n  most_recent = true\n  owners      = [{}]\n  filter {{\n    name   = \"name\"\n    values = [{}]\n  }}\n  filter {{\n    name   = \"virtualization-type\"\n    values = [\"hvm\"]\n  }}\n}}\n", name.replace('_', " "), q(owner), q(pattern)));
    }

    for v in d.nodes.iter().filter(|n| n.kind == "vpc") {
        adopt(format!("aws_vpc.{}", v.label), p(v, "aws_id"));
        m.push_str(&format!("\n# ---- VPC {} ({})\nresource \"aws_vpc\" \"{}\" {{\n  cidr_block           = {}\n  enable_dns_support   = true\n  enable_dns_hostnames = true\n{}}}\n", v.label, p(v, "cidr"), v.label, q(p(v, "cidr")), tags(v, &[])));
        let kids: Vec<&Node> = d.descendants(&v.id).iter().skip(1).filter_map(|id| d.node(id)).collect();
        for s in kids.iter().filter(|n| n.kind == "subnet") {
            adopt(format!("aws_subnet.{}", s.label), p(s, "aws_id"));
            m.push_str(&format!("\n# subnet {} ({} tier, AZ {})\nresource \"aws_subnet\" \"{}\" {{\n  vpc_id            = aws_vpc.{}.id\n  cidr_block        = {}\n  availability_zone = \"${{var.region}}{}\"\n  # public addresses are given per instance (each costs money), not to every instance of the subnet\n  map_public_ip_on_launch = false\n{}}}\n",
                s.label, p(s, "tier"), p(s, "az"), s.label, v.label, q(p(s, "cidr")), p(s, "az"), tags(s, &[("tier", p(s, "tier"))])));
        }
        for g in kids.iter().filter(|n| n.kind == "igw") {
            adopt(format!("aws_internet_gateway.{}", g.label), p(g, "aws_id"));
            m.push_str(&format!("\n# Internet Gateway {}\nresource \"aws_internet_gateway\" \"{}\" {{\n  vpc_id = aws_vpc.{}.id\n{}}}\n", g.label, g.label, v.label, tags(g, &[])));
        }
        let igw = kids.iter().find(|n| n.kind == "igw").map(|n| n.label.clone());
        for n in kids.iter().filter(|n| n.kind == "nat") {
            let sub = n.parent.as_ref().map(|s| label(s)).unwrap_or_default();
            adopt(format!("aws_nat_gateway.{}", n.label), p(n, "aws_id"));
            adopt(format!("aws_eip.{}", n.label), p(n, "eip_alloc"));
            m.push_str(&format!("\n# NAT Gateway {} in {} (about USD {:.0} a month idle: see the Costs tab)\nresource \"aws_eip\" \"{}\" {{\n  domain = \"vpc\"\n{}}}\n\nresource \"aws_nat_gateway\" \"{}\" {{\n  allocation_id = aws_eip.{}.id\n  subnet_id     = aws_subnet.{}.id\n{}{}}}\n",
                n.label, sub, crate::pricing::nat_hourly(&d.region) * crate::pricing::HOURS, n.label, tags(n, &[]), n.label, n.label, sub,
                igw.as_ref().map(|g| format!("  depends_on    = [aws_internet_gateway.{g}]\n")).unwrap_or_default(), tags(n, &[])));
        }
        for rt in kids.iter().filter(|n| n.kind == "rt") {
            adopt(format!("aws_route_table.{}", rt.label), p(rt, "aws_id"));
            m.push_str(&format!("\n# route table {}\nresource \"aws_route_table\" \"{}\" {{\n  vpc_id = aws_vpc.{}.id\n{}}}\n", rt.label, rt.label, v.label, tags(rt, &[])));
            for (i, e) in d.edges.iter().filter(|e| e.kind == "route" && e.source == rt.id).enumerate() {
                let Some(t) = d.node(&e.target) else { continue };
                if !p(rt, "aws_id").is_empty() && matches!(t.kind.as_str(), "igw" | "nat") {
                    adopt(format!("aws_route.{}_{i}", rt.label), &format!("{}_{}", p(rt, "aws_id"), e.params.get("dest").and_then(|v| v.as_str()).unwrap_or("0.0.0.0/0")));
                }
                let target = match t.kind.as_str() {
                    "igw" => format!("gateway_id             = aws_internet_gateway.{}.id", t.label),
                    "nat" => format!("nat_gateway_id         = aws_nat_gateway.{}.id", t.label),
                    _ => continue, // a gateway endpoint adds its own routes (route_table_ids)
                };
                m.push_str(&format!("\nresource \"aws_route\" \"{}_{i}\" {{\n  route_table_id         = aws_route_table.{}.id\n  destination_cidr_block = {}\n  {target}\n}}\n", rt.label, rt.label, q(e.params.get("dest").and_then(|v| v.as_str()).unwrap_or("0.0.0.0/0"))));
            }
            for e in d.edges.iter().filter(|e| e.kind == "attach" && e.target == rt.id) {
                if e.params.get("implicit").and_then(|v| v.as_bool()).unwrap_or(false) {
                    continue; // the subnet uses the VPC's main table by default: there is no association to write or adopt
                }
                let s = label(&e.source);
                if let (Some(sn), false) = (d.node(&e.source), p(rt, "aws_id").is_empty()) {
                    if !p(sn, "aws_id").is_empty() {
                        adopt(format!("aws_route_table_association.{s}"), &format!("{}/{}", p(sn, "aws_id"), p(rt, "aws_id")));
                    }
                }
                m.push_str(&format!("\nresource \"aws_route_table_association\" \"{s}\" {{\n  subnet_id      = aws_subnet.{s}.id\n  route_table_id = aws_route_table.{}.id\n}}\n", rt.label));
            }
        }
        for g in kids.iter().filter(|n| n.kind == "sg") {
            let desc = if p(g, "description").trim().is_empty() { format!("{} ({})", g.label, project) } else { p(g, "description").to_string() };
            let is_default = g.params.get("aws_default").and_then(|v| v.as_bool()).unwrap_or(false);
            let gtype = if is_default { "aws_default_security_group" } else { "aws_security_group" };
            adopt(format!("{gtype}.{}", g.label), p(g, "aws_id"));
            if is_default {
                m.push_str(&format!("\n# the VPC's default security group (AWS makes it; this only manages its rules)\nresource \"aws_default_security_group\" \"{}\" {{\n  vpc_id = aws_vpc.{}.id\n{}}}\n", g.label, v.label, tags(g, &[])));
            } else {
                // an adopted group keeps its real name and description: both force a replacement when changed
                let name = if p(g, "group_name").trim().is_empty() { format!("\"${{var.project}}-{}\"", g.label) } else { q(p(g, "group_name")) };
                m.push_str(&format!("\n# security group {}\nresource \"aws_security_group\" \"{}\" {{\n  name        = {name}\n  description = {}\n  vpc_id      = aws_vpc.{}.id\n{}}}\n", g.label, g.label, q(&desc), v.label, tags(g, &[])));
            };
            // ingress: every traffic arrow into the group
            let gref = format!("{gtype}.{}", g.label);
            for (i, e) in d.edges.iter().filter(|e| e.kind == "traffic" && e.target == g.id).enumerate() {
                let Some(src) = d.node(&e.source) else { continue };
                adopt(format!("aws_vpc_security_group_ingress_rule.{}_in_{i}", g.label), e.params.get("aws_id").and_then(|v| v.as_str()).unwrap_or(""));
                m.push_str(&rule("ingress", &format!("{}_in_{i}", g.label), &gref, src, e, &format!("in from {}", src.label), &group_ref));
            }
            if p(g, "egress") == "rules" {
                for (i, e) in d.edges.iter().filter(|e| e.kind == "traffic" && e.source == g.id).enumerate() {
                    let Some(dst) = d.node(&e.target) else { continue };
                    adopt(format!("aws_vpc_security_group_egress_rule.{}_out_{i}", g.label), e.params.get("aws_id_out").and_then(|v| v.as_str()).unwrap_or(""));
                    m.push_str(&rule("egress", &format!("{}_out_{i}", g.label), &gref, dst, e, &format!("out to {}", dst.label), &group_ref));
                }
            } else {
                adopt(format!("aws_vpc_security_group_egress_rule.{}_out_all", g.label), p(g, "egress_rule_id"));
                m.push_str(&format!("\n# {}: everything out (AWS's default; the provider removes it unless it is written down)\nresource \"aws_vpc_security_group_egress_rule\" \"{}_out_all\" {{\n  security_group_id = {gref}.id\n  ip_protocol       = \"-1\"\n  cidr_ipv4         = \"0.0.0.0/0\"\n}}\n", g.label, g.label));
            }
        }
        for o in kids.iter().filter(|n| n.kind == "other") {
            m.push_str(&format!("\n# other: {} ({}, {}) exists in this VPC; the palette has no block for it and nothing here manages it\n", o.label, p(o, "what").replace('_', " "), p(o, "aws_id")));
        }
        for ep in kids.iter().filter(|n| n.kind == "vpce") {
            let svc = p(ep, "service");
            adopt(format!("aws_vpc_endpoint.{}", ep.label), p(ep, "aws_id"));
            if crate::model::endpoint_type(svc) == Some("gateway") {
                let tables: Vec<String> = d.edges.iter().filter(|e| e.kind == "route" && e.target == ep.id).filter_map(|e| d.node(&e.source)).map(|t| format!("aws_route_table.{}.id", t.label)).collect();
                m.push_str(&format!("\n# gateway endpoint {} for {} (free): the route tables get a route to the service's prefix list\nresource \"aws_vpc_endpoint\" \"{}\" {{\n  vpc_id            = aws_vpc.{}.id\n  service_name      = \"com.amazonaws.${{var.region}}.{svc}\"\n  vpc_endpoint_type = \"Gateway\"\n  route_table_ids   = [{}]\n{}}}\n", ep.label, svc, ep.label, v.label, tables.join(", "), tags(ep, &[])));
            } else {
                let tier = p(ep, "tier");
                let subs: Vec<String> = kids.iter().filter(|n| n.kind == "subnet" && p(n, "tier") == tier).map(|s| format!("aws_subnet.{}.id", s.label)).collect();
                let sg = d.node(p(ep, "sg")).map(|g| format!("  security_group_ids  = [aws_security_group.{}.id]\n", g.label)).unwrap_or_default();
                m.push_str(&format!("\n# interface endpoint {} for {} (one interface per {tier} subnet, USD 0.01/h each)\nresource \"aws_vpc_endpoint\" \"{}\" {{\n  vpc_id              = aws_vpc.{}.id\n  service_name        = \"com.amazonaws.${{var.region}}.{svc}\"\n  vpc_endpoint_type   = \"Interface\"\n  subnet_ids          = [{}]\n{sg}  private_dns_enabled = true\n{}}}\n", ep.label, svc, ep.label, v.label, subs.join(", "), tags(ep, &[])));
            }
        }
        for g in kids.iter().filter(|n| n.kind == "asg") {
            let t = p(g, "type");
            let arch = instance_type(t).map(|x| x.3).unwrap_or("x86_64");
            let (ami, _, _) = ami_for(p(g, "os"), arch);
            let subs: Vec<String> = kids.iter().filter(|n| n.kind == "subnet" && p(n, "tier") == p(g, "tier")).map(|s| format!("aws_subnet.{}.id", s.label)).collect();
            let sgs: Vec<String> = g.params.get("sgs").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|v| v.as_str()).filter(|id| d.node(id).is_some()).map(|id| format!("{}.id", sg_ref(id))).collect()).unwrap_or_default();
            let spot = g.params.get("spot").and_then(|v| v.as_bool()).unwrap_or(false);
            let disk = g.params.get("disk").and_then(|v| v.as_u64()).unwrap_or(8);
            let num = |k: &str, dflt: u64| g.params.get(k).and_then(|v| v.as_u64()).unwrap_or(dflt);
            adopt(format!("aws_autoscaling_group.{}", g.label), p(g, "aws_id"));
            adopt(format!("aws_launch_template.{}", g.label), p(g, "lt_id"));
            let asg_start = m.len();
            let tgs: Vec<String> = d.edges.iter().filter(|e| e.kind == "target" && e.target == g.id).filter_map(|e| d.node(&e.source)).map(|lb| format!("aws_lb_target_group.{}.arn", lb.label)).collect();
            m.push_str(&format!("\n# Auto Scaling group {} ({t}{}, {}–{} instances, desired {})\nresource \"aws_launch_template\" \"{}\" {{\n  name_prefix   = \"${{var.project}}-{}-\"\n  image_id      = data.aws_ami.{ami}.id\n  instance_type = {}\n{}  vpc_security_group_ids = [{}]\n{}  block_device_mappings {{\n    device_name = \"/dev/xvda\"\n    ebs {{\n      volume_type = \"gp3\"\n      volume_size = {disk}\n    }}\n  }}\n  metadata_options {{\n    http_tokens = \"required\"\n  }}\n  tag_specifications {{\n    resource_type = \"instance\"\n    tags = {{ Name = \"${{var.project}}-{}\", \"design-block\" = {} }}\n  }}\n}}\n\nresource \"aws_autoscaling_group\" \"{}\" {{\n  name                = \"${{var.project}}-{}\"\n  min_size            = {}\n  max_size            = {}\n  desired_capacity    = {}\n  vpc_zone_identifier = [{}]\n{}  launch_template {{\n    id      = aws_launch_template.{}.id\n    version = \"$Latest\"\n  }}\n  tag {{\n    key                 = \"design-block\"\n    value               = {}\n    propagate_at_launch = false\n  }}\n}}\n",
                g.label, if spot { ", spot" } else { "" }, num("min", 1), num("max", 2), num("desired", 1), g.label, g.label, q(t),
                if p(g, "key").trim().is_empty() { String::new() } else { "  key_name      = var.key_name\n".to_string() }, sgs.join(", "),
                if spot { "  instance_market_options {\n    market_type = \"spot\"\n  }\n".to_string() } else { String::new() }, g.label, q(&g.label),
                g.label, g.label, num("min", 1), num("max", 2), num("desired", 1), subs.join(", "),
                if tgs.is_empty() { String::new() } else { format!("  target_group_arns   = [{}]\n  health_check_type   = \"ELB\"\n", tgs.join(", ")) }, g.label, q(&g.label)));
            if !p(g, "aws_id").trim().is_empty() {
                let tail = m.split_off(asg_start);
                let tail = tail.replacen(&format!("  name                = \"${{var.project}}-{}\"\n", g.label), &format!("  name                = {}\n", q(p(g, "aws_id"))), 1);
                let tail = if p(g, "lt_name").trim().is_empty() { tail } else { tail.replacen(&format!("  name_prefix   = \"${{var.project}}-{}-\"\n", g.label), &format!("  name          = {}\n", q(p(g, "lt_name"))), 1) };
                let tail = if p(g, "image_id").trim().is_empty() { tail } else { tail.replacen(&format!("  image_id      = data.aws_ami.{ami}.id\n"), &format!("  image_id      = {}\n", q(p(g, "image_id"))), 1) };
                let tail = if p(g, "key").trim().is_empty() { tail } else { tail.replacen("  key_name      = var.key_name\n", &format!("  key_name      = {}\n", q(p(g, "key"))), 1) };
                m.push_str(&tail);
            }
        }
        for lb in kids.iter().filter(|n| n.kind == "alb") {
            let subs: Vec<String> = kids.iter().filter(|n| n.kind == "subnet" && p(n, "tier") == p(lb, "tier")).map(|s| format!("aws_subnet.{}.id", s.label)).collect();
            let sg = d.node(p(lb, "sg")).map(|g| format!("aws_security_group.{}.id", g.label));
            let port = lb.params.get("port").and_then(|v| v.as_u64()).unwrap_or(80);
            let cert = p(lb, "cert").trim();
            let targets: Vec<(&crate::model::Edge, &Node)> = d.edges.iter().filter(|e| e.kind == "target" && e.source == lb.id).filter_map(|e| Some((e, d.node(&e.target)?))).collect();
            let tport = targets.first().map(|(e, _)| e.params.get("port").and_then(|v| v.as_u64()).unwrap_or(8080)).unwrap_or(8080);
            adopt(format!("aws_lb.{}", lb.label), p(lb, "aws_id"));
            adopt(format!("aws_lb_target_group.{}", lb.label), p(lb, "tg_arn"));
            adopt(format!("aws_lb_listener.{}", lb.label), p(lb, "listener_arn"));
            let lb_start = m.len();
            m.push_str(&format!("\n# load balancer {} ({}, about USD {:.0} a month idle + LCU)\nresource \"aws_lb\" \"{}\" {{\n  name               = substr(\"${{var.project}}-{}\", 0, 32)\n  load_balancer_type = \"application\"\n  internal           = {}\n  subnets            = [{}]\n{}{}}}\n\nresource \"aws_lb_target_group\" \"{}\" {{\n  name     = substr(\"${{var.project}}-{}\", 0, 32)\n  port     = {tport}\n  protocol = \"HTTP\"\n  vpc_id   = aws_vpc.{}.id\n  health_check {{\n    path = {}\n  }}\n{}}}\n",
                lb.label, p(lb, "scheme"), crate::pricing::alb_hourly(&d.region) * crate::pricing::HOURS, lb.label, lb.label.replace('_', "-"), p(lb, "scheme") == "internal", subs.join(", "),
                sg.map(|s| format!("  security_groups    = [{s}]\n")).unwrap_or_default(), tags(lb, &[]), lb.label, lb.label.replace('_', "-"), v.label, q(if p(lb, "health").is_empty() { "/" } else { p(lb, "health") }), tags(lb, &[])));
            // an adopted balancer keeps its real names (a name change rebuilds it) and type
            if !p(lb, "lb_name").trim().is_empty() {
                let tail = m.split_off(lb_start);
                let tail = tail.replacen(&format!("  name               = substr(\"${{var.project}}-{}\", 0, 32)\n", lb.label.replace('_', "-")), &format!("  name               = {}\n", q(p(lb, "lb_name"))), 1)
                    .replacen(&format!("  name     = substr(\"${{var.project}}-{}\", 0, 32)\n", lb.label.replace('_', "-")), &format!("  name     = {}\n", q(p(lb, "tg_name"))), 1);
                let tail = if p(lb, "lb_type").is_empty() { tail } else { tail.replacen("  load_balancer_type = \"application\"\n", &format!("  load_balancer_type = {}\n", q(p(lb, "lb_type"))), 1) };
                m.push_str(&tail);
            }
            if cert.is_empty() {
                m.push_str(&format!("\nresource \"aws_lb_listener\" \"{}\" {{\n  load_balancer_arn = aws_lb.{}.arn\n  port              = {port}\n  protocol          = \"HTTP\"\n  default_action {{\n    type             = \"forward\"\n    target_group_arn = aws_lb_target_group.{}.arn\n  }}\n}}\n", lb.label, lb.label, lb.label));
            } else {
                m.push_str(&format!("\nresource \"aws_lb_listener\" \"{}\" {{\n  load_balancer_arn = aws_lb.{}.arn\n  port              = {port}\n  protocol          = \"HTTPS\"\n  ssl_policy        = \"ELBSecurityPolicy-TLS13-1-2-2021-06\"\n  certificate_arn   = {}\n  default_action {{\n    type             = \"forward\"\n    target_group_arn = aws_lb_target_group.{}.arn\n  }}\n}}\n\n# plain HTTP is sent to HTTPS\nresource \"aws_lb_listener\" \"{}_http\" {{\n  load_balancer_arn = aws_lb.{}.arn\n  port              = 80\n  protocol          = \"HTTP\"\n  default_action {{\n    type = \"redirect\"\n    redirect {{\n      port        = \"443\"\n      protocol    = \"HTTPS\"\n      status_code = \"HTTP_301\"\n    }}\n  }}\n}}\n", lb.label, lb.label, q(cert), lb.label, lb.label, lb.label));
            }
            for (e, t) in targets.iter().filter(|(_, t)| t.kind == "ec2") {
                m.push_str(&format!("\nresource \"aws_lb_target_group_attachment\" \"{}_{}\" {{\n  target_group_arn = aws_lb_target_group.{}.arn\n  target_id        = aws_instance.{}.id\n  port             = {}\n}}\n", lb.label, t.label, lb.label, t.label, e.params.get("port").and_then(|v| v.as_u64()).unwrap_or(8080)));
            }
        }
        for n in kids.iter().filter(|n| n.kind == "ec2") {
            let t = p(n, "type");
            let arch = instance_type(t).map(|x| x.3).unwrap_or("x86_64");
            let (ami, _, _) = ami_for(p(n, "os"), arch);
            let ami_ref = if p(n, "image_id").trim().is_empty() { format!("data.aws_ami.{ami}.id") } else { q(p(n, "image_id")) };
            let adopted = !p(n, "aws_id").trim().is_empty();
            adopt(format!("aws_instance.{}", n.label), p(n, "aws_id"));
            let sub = n.parent.as_ref().map(|s| label(s)).unwrap_or_default();
            let sgs: Vec<String> = n.params.get("sgs").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|v| v.as_str()).filter(|id| d.node(id).is_some()).map(|id| format!("{}.id", sg_ref(id))).collect()).unwrap_or_default();
            let public = n.params.get("public_ip").and_then(|v| v.as_bool()).unwrap_or(false);
            let spot = n.params.get("spot").and_then(|v| v.as_bool()).unwrap_or(false);
            let disk = n.params.get("disk").and_then(|v| v.as_u64()).unwrap_or(8);
            let monthly = crate::pricing::instance_hourly(t, &d.region) * crate::pricing::HOURS * if spot { crate::pricing::SPOT_FACTOR } else { 1.0 };
            // an adopted instance keeps the address setting it has (writing it would force a rebuild; an Elastic IP reads as false)
            let public_line = if adopted { String::new() } else { format!("  associate_public_ip_address = {public}\n") };
            m.push_str(&format!("\n# instance {} ({t}{}, about USD {monthly:.0} a month running)\nresource \"aws_instance\" \"{}\" {{\n  ami                         = {ami_ref}\n  instance_type               = {}\n  subnet_id                   = aws_subnet.{sub}.id\n  vpc_security_group_ids      = [{}]\n{public_line}{}{}  root_block_device {{\n    volume_type = \"gp3\"\n    volume_size = {disk}\n  }}\n  metadata_options {{\n    http_tokens = \"required\"\n  }}\n{}}}\n",
                n.label, if spot { ", spot" } else { "" }, n.label, q(t), sgs.join(", "), if p(n, "key").trim().is_empty() { String::new() } else if !p(n, "aws_id").trim().is_empty() { format!("  key_name                    = {}\n", q(p(n, "key"))) } else { "  key_name                    = var.key_name\n".to_string() }
                    + &if p(n, "iam_profile").trim().is_empty() { String::new() } else { format!("  iam_instance_profile        = {}\n", q(p(n, "iam_profile"))) },
                if spot { "  # spot: about 70 % cheaper; stopped (not terminated) when AWS takes the capacity back, so the volume and the work on it stay\n  instance_market_options {\n    market_type = \"spot\"\n    spot_options {\n      spot_instance_type             = \"persistent\"\n      instance_interruption_behavior = \"stop\"\n    }\n  }\n".to_string() } else { String::new() }, tags(n, &[])));
        }
    }

    for b in d.nodes.iter().filter(|n| n.kind == "s3") {
        let life = p(b, "lifecycle");
        let expire = b.params.get("expire_days").and_then(|x| x.as_u64()).unwrap_or(0);
        m.push_str(&format!("\n# ---- S3 bucket {} (public access blocked, encrypted; AWS adds a unique suffix to the name)\nresource \"aws_s3_bucket\" \"{}\" {{\n  bucket_prefix = \"${{var.project}}-{}-\"\n{}}}\n\nresource \"aws_s3_bucket_public_access_block\" \"{}\" {{\n  bucket                  = aws_s3_bucket.{}.id\n  block_public_acls       = true\n  block_public_policy     = true\n  ignore_public_acls      = true\n  restrict_public_buckets = true\n}}\n\nresource \"aws_s3_bucket_server_side_encryption_configuration\" \"{}\" {{\n  bucket = aws_s3_bucket.{}.id\n  rule {{\n    apply_server_side_encryption_by_default {{\n      sse_algorithm = \"AES256\"\n    }}\n  }}\n}}\n",
            b.label, b.label, b.label.replace('_', "-"), tags(b, &[]), b.label, b.label, b.label, b.label));
        if b.params.get("versioning").and_then(|x| x.as_bool()).unwrap_or(false) {
            m.push_str(&format!("\nresource \"aws_s3_bucket_versioning\" \"{}\" {{\n  bucket = aws_s3_bucket.{}.id\n  versioning_configuration {{\n    status = \"Enabled\"\n  }}\n}}\n", b.label, b.label));
        }
        if life != "none" || expire > 0 {
            let mut rule = String::new();
            if life == "ia-30" || life == "ia-30-glacier-90" {
                rule.push_str("    transition {\n      days          = 30\n      storage_class = \"STANDARD_IA\"\n    }\n");
            }
            if life == "glacier-90" || life == "ia-30-glacier-90" {
                rule.push_str("    transition {\n      days          = 90\n      storage_class = \"GLACIER_IR\"\n    }\n");
            }
            if expire > 0 {
                rule.push_str(&format!("    expiration {{\n      days = {expire}\n    }}\n"));
            }
            m.push_str(&format!("\n# {}: older objects move to cheaper storage\nresource \"aws_s3_bucket_lifecycle_configuration\" \"{}\" {{\n  bucket = aws_s3_bucket.{}.id\n  rule {{\n    id     = \"age\"\n    status = \"Enabled\"\n    filter {{}}\n{rule}  }}\n}}\n", b.label, b.label, b.label));
        }
    }

    // variables
    let mut v = String::new();
    v.push_str("# variables.tf: generated by AWS Infra Builder\n\n");
    v.push_str(&format!("variable \"region\" {{\n  description = \"the AWS region of the design\"\n  type        = string\n  default     = {}\n}}\n\n", q(&d.region)));
    v.push_str(&format!("variable \"project\" {{\n  description = \"the project tag and the prefix of every Name\"\n  type        = string\n  default     = {}\n}}\n", q(&project)));
    let keys: Vec<&str> = d.nodes.iter().filter(|n| n.kind == "ec2" || n.kind == "asg").map(|n| p(n, "key").trim()).filter(|k| !k.is_empty()).collect();
    if let Some(k) = keys.first() {
        v.push_str(&format!("\nvariable \"key_name\" {{\n  description = \"the name of an existing EC2 key pair in the region, for SSH\"\n  type        = string\n  default     = {}\n}}\n", q(k)));
    }

    // Lambda functions: code zipped by the archive provider, a role that may only do what the function does, a schedule in the
    // owner's time zone (EventBridge Scheduler; free)
    for f in d.nodes.iter().filter(|n| n.kind == "lambda") {
        let action = p(f, "action");
        let inst: Vec<String> = f.params.get("instances").and_then(|v| v.as_array()).map(|a| a.iter().filter_map(|v| v.as_str()).filter(|id| d.node(id).map(|n| n.kind == "ec2").unwrap_or(false)).map(label).collect()).unwrap_or_default();
        let refs_id: Vec<String> = inst.iter().map(|l| format!("aws_instance.{l}.id")).collect();
        let refs_arn: Vec<String> = inst.iter().map(|l| format!("aws_instance.{l}.arn")).collect();
        let code = if matches!(action, "stop" | "start") {
            format!("import os\nimport boto3\n\n\ndef handler(event, context):\n    ids = [i for i in os.environ.get(\"INSTANCE_IDS\", \"\").split(\",\") if i]\n    if not ids:\n        return {{\"{action}ed\": []}}\n    ec2 = boto3.client(\"ec2\")\n    ec2.{action}_instances(InstanceIds=ids)\n    return {{\"{action}ed\": ids}}\n")
        } else if p(f, "code").trim().is_empty() {
            "def handler(event, context):\n    return {\"ok\": True}\n".to_string()
        } else {
            p(f, "code").to_string()
        };
        let memory = f.params.get("memory").and_then(|v| v.as_u64()).unwrap_or(128);
        let timeout = f.params.get("timeout").and_then(|v| v.as_u64()).unwrap_or(30);
        let runtime = if p(f, "runtime").is_empty() { "python3.12" } else { p(f, "runtime") };
        let l = &f.label;
        m.push_str(&format!("\n# ---- Lambda function {l} ({}; free tier)\ndata \"archive_file\" \"{l}\" {{\n  type        = \"zip\"\n  output_path = \"${{path.module}}/{l}.zip\"\n  source {{\n    filename = \"index.py\"\n    content  = <<-EOT\n{}\n    EOT\n  }}\n}}\n",
            if matches!(action, "stop" | "start") { format!("{action}s {}", if inst.is_empty() { "nothing yet".to_string() } else { inst.join(", ") }) } else { "custom code".to_string() },
            code.lines().map(|ln| format!("      {ln}")).collect::<Vec<_>>().join("\n")));
        m.push_str(&format!("\nresource \"aws_iam_role\" \"{l}\" {{\n  name_prefix        = \"${{var.project}}-{l}-\"\n  assume_role_policy = jsonencode({{\n    Version = \"2012-10-17\"\n    Statement = [{{ Effect = \"Allow\", Principal = {{ Service = \"lambda.amazonaws.com\" }}, Action = \"sts:AssumeRole\" }}]\n  }})\n}}\n"));
        let ec2_stmt = if matches!(action, "stop" | "start") {
            format!(",\n      {{ Effect = \"Allow\", Action = [\"ec2:{}Instances\"], Resource = [{}] }}", if action == "stop" { "Stop" } else { "Start" }, if refs_arn.is_empty() { "\"*\"".to_string() } else { refs_arn.join(", ") })
        } else { String::new() };
        m.push_str(&format!("\nresource \"aws_iam_role_policy\" \"{l}\" {{\n  role = aws_iam_role.{l}.id\n  policy = jsonencode({{\n    Version = \"2012-10-17\"\n    Statement = [\n      {{ Effect = \"Allow\", Action = [\"logs:CreateLogGroup\", \"logs:CreateLogStream\", \"logs:PutLogEvents\"], Resource = \"arn:aws:logs:*:*:*\" }}{ec2_stmt}\n    ]\n  }})\n}}\n"));
        m.push_str(&format!("\nresource \"aws_lambda_function\" \"{l}\" {{\n  function_name    = \"${{var.project}}-{l}\"\n  role             = aws_iam_role.{l}.arn\n  handler          = \"index.handler\"\n  runtime          = \"{runtime}\"\n  memory_size      = {memory}\n  timeout          = {timeout}\n  filename         = data.archive_file.{l}.output_path\n  source_code_hash = data.archive_file.{l}.output_base64sha256\n{}  tags = {{ Name = \"{l}\", \"design-block\" = \"{}\" }}\n}}\n",
            if refs_id.is_empty() { String::new() } else { format!("  environment {{\n    variables = {{\n      INSTANCE_IDS = join(\",\", [{}])\n    }}\n  }}\n", refs_id.join(", ")) }, f.id));
        let time = p(f, "time");
        if crate::checks::valid_time(time) {
            let (hh, mm) = time.split_once(':').unwrap();
            let (h, mi) = (hh.parse::<u8>().unwrap_or(0), mm.parse::<u8>().unwrap_or(0));
            let cron = match p(f, "days") { "daily" => format!("cron({mi} {h} * * ? *)"), "weekends" => format!("cron({mi} {h} ? * SAT,SUN *)"), _ => format!("cron({mi} {h} ? * MON-FRI *)") };
            let tz = if p(f, "tz").is_empty() { "UTC" } else { p(f, "tz") };
            m.push_str(&format!("\n# {l}: runs at {time} ({}) in {tz}\nresource \"aws_iam_role\" \"{l}_schedule\" {{\n  name_prefix        = \"${{var.project}}-{l}-sch-\"\n  assume_role_policy = jsonencode({{\n    Version = \"2012-10-17\"\n    Statement = [{{ Effect = \"Allow\", Principal = {{ Service = \"scheduler.amazonaws.com\" }}, Action = \"sts:AssumeRole\" }}]\n  }})\n}}\n\nresource \"aws_iam_role_policy\" \"{l}_schedule\" {{\n  role = aws_iam_role.{l}_schedule.id\n  policy = jsonencode({{\n    Version = \"2012-10-17\"\n    Statement = [{{ Effect = \"Allow\", Action = [\"lambda:InvokeFunction\"], Resource = aws_lambda_function.{l}.arn }}]\n  }})\n}}\n\nresource \"aws_scheduler_schedule\" \"{l}\" {{\n  name                         = \"${{var.project}}-{l}\"\n  schedule_expression          = \"{cron}\"\n  schedule_expression_timezone = \"{tz}\"\n  flexible_time_window {{\n    mode = \"OFF\"\n  }}\n  target {{\n    arn      = aws_lambda_function.{l}.arn\n    role_arn = aws_iam_role.{l}_schedule.arn\n  }}\n}}\n", p(f, "days")));
        }
    }

    // outputs
    let mut o = String::new();
    o.push_str("# outputs.tf: generated by AWS Infra Builder\n");
    for n in d.nodes.iter().filter(|n| n.kind == "vpc") {
        o.push_str(&format!("\noutput \"vpc_{}_id\" {{\n  value = aws_vpc.{}.id\n}}\n", n.label, n.label));
    }
    let subnets: Vec<&Node> = d.nodes.iter().filter(|n| n.kind == "subnet").collect();
    if !subnets.is_empty() {
        o.push_str("\noutput \"subnet_ids\" {\n  value = {\n");
        for s in subnets {
            o.push_str(&format!("    {} = aws_subnet.{}.id\n", s.label, s.label));
        }
        o.push_str("  }\n}\n");
    }
    for n in d.nodes.iter().filter(|n| n.kind == "nat") {
        o.push_str(&format!("\noutput \"nat_{}_public_ip\" {{\n  value = aws_eip.{}.public_ip\n}}\n", n.label, n.label));
    }
    for lb in d.nodes.iter().filter(|n| n.kind == "alb") {
        o.push_str(&format!("\noutput \"{}_dns_name\" {{\n  value = aws_lb.{}.dns_name\n}}\n", lb.label, lb.label));
    }
    for b in d.nodes.iter().filter(|n| n.kind == "s3") {
        o.push_str(&format!("\noutput \"bucket_{}\" {{\n  value = aws_s3_bucket.{}.bucket\n}}\n", b.label, b.label));
    }
    for n in d.nodes.iter().filter(|n| n.kind == "ec2") {
        let public = n.params.get("public_ip").and_then(|v| v.as_bool()).unwrap_or(false);
        o.push_str(&format!("\noutput \"instance_{}\" {{\n  value = {{\n    id         = aws_instance.{}.id\n    private_ip = aws_instance.{}.private_ip\n{}  }}\n}}\n", n.label, n.label, n.label,
            if public { format!("    public_ip  = aws_instance.{}.public_ip\n", n.label) } else { String::new() }));
    }

    let mut files = Files::new();
    files.insert("main.tf".into(), m);
    files.insert("variables.tf".into(), v);
    files.insert("outputs.tf".into(), o);
    if !imports.is_empty() {
        let mut t = String::from("# imports.tf: generated by AWS Infra Builder. These resources already exist (the design was imported, or carries their ids):\n# the first apply adopts them into the state instead of creating them again. Nothing is created or changed by an import block.\n");
        for (to, id) in &imports {
            t.push_str(&format!("\nimport {{\n  to = {to}\n  id = {}\n}}\n", q(id)));
        }
        files.insert("imports.tf".into(), t);
    }
    files
}

/// one ingress or egress rule from a traffic arrow; `other` is the group or address range at the far end
fn rule(dir: &str, name: &str, group: &str, other: &Node, e: &crate::model::Edge, comment: &str, group_ref: &dyn Fn(&Node) -> String) -> String {
    let proto = e.params.get("proto").and_then(|v| v.as_str()).unwrap_or("tcp").to_lowercase();
    let ports = e.params.get("ports").and_then(|v| v.as_str()).unwrap_or("");
    let (ip_protocol, port_lines) = match proto.as_str() {
        "all" | "-1" => ("-1".to_string(), String::new()),
        "icmp" => ("icmp".to_string(), "  from_port         = -1\n  to_port           = -1\n".to_string()),
        _ => match parse_ports(&proto, ports) {
            Ok((0, 65535)) => (proto.clone(), "  from_port         = 0\n  to_port           = 65535\n".to_string()),
            Ok((a, b)) => (proto.clone(), format!("  from_port         = {a}\n  to_port           = {b}\n")),
            Err(_) => (proto.clone(), "  from_port         = 0\n  to_port           = 65535\n".to_string()),
        },
    };
    let far = if other.kind == "cidr" {
        format!("  cidr_ipv4         = {}\n", q(p(other, "cidr")))
    } else {
        format!("  referenced_security_group_id = {}.id\n", group_ref(other))
    };
    format!("\n# {comment}\nresource \"aws_vpc_security_group_{dir}_rule\" \"{name}\" {{\n  security_group_id = {group}.id\n  ip_protocol       = {}\n{port_lines}{far}}}\n", q(&ip_protocol))
}

/// write the files into a folder (made if missing)
pub fn write_to(files: &Files, dir: &std::path::Path) -> anyhow::Result<()> {
    std::fs::create_dir_all(dir)?;
    for (name, text) in files {
        std::fs::write(dir.join(name), text)?;
    }
    Ok(())
}

